    public void ListarUsuarios() {
        List<Modelo.Usuarios> ListaUsu = usuarioDAO.Listar();
        modelo = (DefaultTableModel) TableUsuarios.getModel();
        modelo.setRowCount(0);

        Object[] ob = new Object[8];
        for (int i = 0; i < ListaUsu.size(); i++) {
            ob[0] = ListaUsu.get(i).getId();
            ob[1] = ListaUsu.get(i).getNombre();
            ob[2] = ListaUsu.get(i).getCorreo();
            ob[3] = ListaUsu.get(i).getTipoNombre();   // ← era getTipoUsuario()
            ob[4] = ListaUsu.get(i).getNacimiento();
            ob[5] = ListaUsu.get(i).getTelefono();
            ob[6] = ListaUsu.get(i).getEstado();
            ob[7] = ListaUsu.get(i).getCreatedAt();
            modelo.addRow(ob);
        }
        TableUsuarios.setModel(modelo);
        aplicarColorEstadoUsu(); // lo llamas desde aquí

        // Activa o desactiva los botones según sea el estado del cliente
        TableUsuarios.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && TableUsuarios.getSelectedRow() != -1) {

                int fila = TableUsuarios.getSelectedRow();
                Object estado = TableUsuarios.getValueAt(fila, 6);

                int estadoVal = Integer.parseInt(estado.toString().trim());

                if (estadoVal == 1) {
                    btnEstadoUsu.setEnabled(true);    // Boton Activo
                    btnGuardarUsu.setEnabled(true);     // Boton Activo
                    btnNuevoUsu.setEnabled(true);       // Boton Activo
                    btnActualizarUsu.setEnabled(true); // Boton Activo
                } else {
                    btnEstadoUsu.setEnabled(true);    // Boton Activo
                    btnGuardarUsu.setEnabled(false);    // Boton inactivo
                    btnNuevoUsu.setEnabled(false);      // Boton inactivo
                    btnActualizarUsu.setEnabled(false);// Boton inactivo
                }
            }
        });
    }

