    private void aplicarColorEstadoUsu() {
        TableUsuarios.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {
                java.awt.Component c = super.getTableCellRendererComponent(
                        table, value, isSelected, hasFocus, row, column);

                Object estado = table.getModel().getValueAt(row, 6); // ← índice 10

                if (!isSelected) {
                    String estadoStr = estado.toString().trim();
                    if (!estadoStr.isEmpty()) { // ← validar que no esté vacío
                        int estadoVal = Integer.parseInt(estadoStr);
                        if (estadoVal == 1) {
                            c.setBackground(new java.awt.Color(232, 255, 234));
                            c.setForeground(new java.awt.Color(0, 120, 0));
                        } else {
                            c.setBackground(new java.awt.Color(189, 189, 189));
                            c.setForeground(new java.awt.Color(245, 73, 39));
                        }
                    }
                }
                return c;
            }
        });

        TableUsuarios.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && TableUsuarios.getSelectedRow() != -1) {

                int fila = TableUsuarios.getSelectedRow();
                Object estado = TableUsuarios.getValueAt(fila, 6);

                int estadoVal = Integer.parseInt(estado.toString().trim());

                if (estadoVal == 1) {
                    btnEstadoUsu.setEnabled(true);    // Boton Activo
                    btnGuardarUsu.setEnabled(false);     // Boton inactivo
                    btnNuevoUsu.setEnabled(true);       // Boton Activo
                    btnActualizarUsu.setEnabled(true); // Boton Activo
                    //tbnExcel.setEnabled(true);// Boton Activo
                    //tbnPDF.setEnabled(true);// Boton Activo
                } else {
                    btnEstadoUsu.setEnabled(true);    // Boton Activo
                    btnGuardarUsu.setEnabled(false);    // Boton inactivo
                    btnNuevoUsu.setEnabled(true);      // Boton Activo
                    btnActualizarUsu.setEnabled(false);// Boton inactivo
                    //tbnExcel.setEnabled(false);// Boton inactivo
                    //tbnPDF.setEnabled(false);// Boton inactivo
                }
            }
        });

        // Ocultar columna ID (índice 0)
        TableUsuarios.getColumnModel().getColumn(0).setMinWidth(0);
        TableUsuarios.getColumnModel().getColumn(0).setMaxWidth(0);
        TableUsuarios.getColumnModel().getColumn(0).setPreferredWidth(0);

        // Ocultar columna Estado (índice 10)
        TableUsuarios.getColumnModel().getColumn(6).setMinWidth(0);
        TableUsuarios.getColumnModel().getColumn(6).setMaxWidth(0);
        TableUsuarios.getColumnModel().getColumn(6).setPreferredWidth(0);
    }

