    private void btnGuardarUsuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarUsuActionPerformed
        // TODO add your handling code here:
        if (txtNombreUsuario.getText().isEmpty()
                || txtCorreoUsuario.getText().isEmpty()
                || txtClaveUsuario.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete los campos obligatorios");
            return;
        }

        // Obtener tipo según el combo
        int tipo = cbxTipo.getSelectedIndex() + 1; // Administrador=1, Cajero=2, Bodega=3

        usuario.setNombre(txtNombreUsuario.getText());
        usuario.setCorreo(txtCorreoUsuario.getText());
        usuario.setTipoUsuario(tipo);
        usuario.setPass(txtClaveUsuario.getText());
        usuario.setNacimiento(jDateChooser1.getDate());
        usuario.setTelefono(txtTelefonoUsuario.getText());

        if (usuarioDAO.Registrar(usuario)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario registrado correctamente");
            Limpiar();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al registrar usuario");
        }
        if (usuarioDAO.Registrar(usuario)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario registrado correctamente");
            Limpiar();
            ListarUsuarios(); // ← agrega
        }
    }//GEN-LAST:event_btnGuardarUsuActionPerformed

    private void btnActualizarUsuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarUsuActionPerformed
        // TODO add your handling code here:
        if (txtIdUsuario.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un usuario primero");
            return;
        }
        int tipo = cbxTipo.getSelectedIndex() + 1;
        usuario.setId(Integer.parseInt(txtIdUsuario.getText()));
        usuario.setNombre(txtNombreUsuario.getText());
        usuario.setCorreo(txtCorreoUsuario.getText());
        usuario.setTipoUsuario(tipo);
        usuario.setPass(txtClaveUsuario.getText());
        usuario.setNacimiento(jDateChooser1.getDate());
        usuario.setTelefono(txtTelefonoUsuario.getText());

        if (usuarioDAO.Modificar(usuario)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente");
            Limpiar();
            ListarUsuarios();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al actualizar usuario");
        }
    }//GEN-LAST:event_btnActualizarUsuActionPerformed

